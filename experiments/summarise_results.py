"""Print the report's tables from ``results/runs.csv``.

Keeping the numbers in the write-up reproducible: every table in the report is
generated by this script rather than copied by hand, so re-running the sweep
re-derives them.

Usage::

    python experiments/summarise_results.py
    python experiments/summarise_results.py --markdown   # ready to paste
"""

from __future__ import annotations

import argparse
import csv
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Callable, Iterable, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from warehouse.metrics import confidence_interval  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
STRATEGIES = ("selfish", "greedy_pgp", "adopt", "cbs", "full_replan")
LABEL = {
    "selfish": "selfish",
    "greedy_pgp": "greedy PGP",
    "adopt": "ADOPT",
    "cbs": "CBS",
    "full_replan": "full replan",
}


def load(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        raise SystemExit(f"{path} not found -- run experiments/run_experiments.py first")
    with path.open(newline="", encoding="utf-8") as handle:
        return [_coerce(row) for row in csv.DictReader(handle)]


def _coerce(row: dict[str, str]) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for key, value in row.items():
        if value in ("", None):
            out[key] = None
        elif value in ("True", "False"):
            out[key] = value == "True"
        else:
            try:
                out[key] = int(value)
            except ValueError:
                try:
                    out[key] = float(value)
                except ValueError:
                    out[key] = value
    return out


def mean(rows: Iterable[dict[str, Any]], key: str) -> float:
    values = [float(r[key]) for r in rows if r.get(key) is not None]
    return sum(values) / len(values) if values else 0.0


def ci(rows: Iterable[dict[str, Any]], key: str) -> float:
    return confidence_interval([float(r[key]) for r in rows if r.get(key) is not None])


class Table:
    """A small text/markdown table."""

    def __init__(self, *headers: str) -> None:
        self.headers = headers
        self.rows: list[Sequence[str]] = []

    def add(self, *cells: Any) -> None:
        self.rows.append([str(c) for c in cells])

    def render(self, markdown: bool) -> str:
        widths = [
            max(len(h), *(len(r[i]) for r in self.rows)) if self.rows else len(h)
            for i, h in enumerate(self.headers)
        ]
        if markdown:
            head = "| " + " | ".join(self.headers) + " |"
            rule = "|" + "|".join("---" for _ in self.headers) + "|"
            body = ["| " + " | ".join(r) + " |" for r in self.rows]
            return "\n".join([head, rule, *body])

        head = "  ".join(h.ljust(w) for h, w in zip(self.headers, widths))
        rule = "  ".join("-" * w for w in widths)
        body = ["  ".join(c.ljust(w) for c, w in zip(r, widths)) for r in self.rows]
        return "\n".join([head, rule, *body])


def section(title: str, markdown: bool) -> None:
    print()
    if markdown:
        print(f"### {title}")
    else:
        print("=" * 78)
        print(title)
        print("=" * 78)
    print()


def headline(rows: list[dict[str, Any]], markdown: bool) -> None:
    section("Headline comparison (disrupted runs, all fleet sizes and densities)", markdown)
    main = [r for r in rows if r["sweep"] == "main" and r["density"] > 0]

    table = Table(
        "strategy", "total steps", "agents changed", "agents consulted",
        "repair ms", "tasks done", "stranded",
    )
    for strategy in STRATEGIES:
        group = [r for r in main if r["strategy"] == strategy]
        if not group:
            continue
        table.add(
            LABEL[strategy],
            f"{mean(group, 'total_timesteps'):.0f} +/- {ci(group, 'total_timesteps'):.0f}",
            f"{mean(group, 'mean_agents_changed'):.2f} +/- {ci(group, 'mean_agents_changed'):.2f}",
            f"{mean(group, 'mean_agents_involved'):.2f}",
            f"{mean(group, 'mean_repair_ms'):.1f}",
            f"{mean(group, 'completion_rate'):.1%}",
            f"{mean(group, 'agents_stranded'):.2f}",
        )
    print(table.render(markdown))
    print()
    print(f"({len(main)} runs; +/- is a 95% confidence interval over seeds.)")


def scaling(rows: list[dict[str, Any]], axis: str, markdown: bool) -> None:
    pretty = "fleet size" if axis == "n_agents" else "obstacle density"
    section(f"Scaling with {pretty}", markdown)
    main = [r for r in rows if r["sweep"] == "main"]
    if axis == "n_agents":
        main = [r for r in main if r["density"] > 0]

    values = sorted({r[axis] for r in main})
    for metric, label, fmt in (
        ("total_timesteps", "Total time steps (all agents)", "{:.0f}"),
        ("mean_agents_changed", "Agents replanned per disruption", "{:.2f}"),
        ("mean_repair_ms", "Repair time per disruption (ms)", "{:.1f}"),
    ):
        print(f"{label}:")
        table = Table(pretty, *(LABEL[s] for s in STRATEGIES))
        for value in values:
            cells = []
            for strategy in STRATEGIES:
                group = [
                    r for r in main if r[axis] == value and r["strategy"] == strategy
                ]
                cells.append(fmt.format(mean(group, metric)) if group else "-")
            table.add(value, *cells)
        print(table.render(markdown))
        print()


def knob(rows: list[dict[str, Any]], sweep: str, axis: str, markdown: bool,
         metrics: Sequence[tuple[str, str, str]]) -> None:
    subset = [r for r in rows if r["sweep"] == sweep]
    if not subset:
        return
    section(f"Parameter sweep: {axis}", markdown)

    table = Table(axis, *(label for _, label, _ in metrics))
    for value in sorted({r[axis] for r in subset}):
        group = [r for r in subset if r[axis] == value]
        table.add(value, *(fmt.format(mean(group, key)) for key, _, fmt in metrics))
    print(table.render(markdown))


def social_laws(rows: list[dict[str, Any]], markdown: bool) -> None:
    subset = [r for r in rows if r["sweep"] == "social_laws"]
    if not subset:
        return
    section("Social laws (one-way aisles, Ch 11 section 3.1)", markdown)

    table = Table("strategy", "no convention", "one-way aisles", "change")
    for strategy in STRATEGIES:
        off = [r for r in subset if r["strategy"] == strategy and not r["social_laws"]]
        on = [r for r in subset if r["strategy"] == strategy and r["social_laws"]]
        if not off or not on:
            continue
        a, b = mean(off, "total_timesteps"), mean(on, "total_timesteps")
        delta = (b - a) / a * 100 if a else 0.0
        table.add(LABEL[strategy], f"{a:.0f}", f"{b:.0f}", f"{delta:+.1f}%")
    print(table.render(markdown))


def robustness(rows: list[dict[str, Any]], markdown: bool) -> None:
    section("Robustness", markdown)
    main = [r for r in rows if r["sweep"] == "main"]

    total_collisions = sum(int(r["collisions_detected"]) for r in main)
    print(f"Collisions in any final joint plan : {total_collisions} (across {len(main)} runs)")

    table = Table(
        "strategy", "repair failures / run", "ADOPT timeouts / run",
        "agents abandoned / run", "safety trims / run",
    )
    for strategy in STRATEGIES:
        group = [r for r in main if r["strategy"] == strategy]
        if not group:
            continue
        table.add(
            LABEL[strategy],
            f"{mean(group, 'repair_failures'):.2f}",
            f"{mean(group, 'solver_timeouts'):.2f}",
            f"{mean(group, 'abandoned_agents'):.2f}",
            f"{mean(group, 'safety_truncations'):.2f}",
        )
    print()
    print(table.render(markdown))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--markdown", action="store_true")
    parser.add_argument("--csv", type=Path, default=RESULTS / "runs.csv")
    args = parser.parse_args()

    rows = load(args.csv)
    print(f"Loaded {len(rows)} runs from {args.csv.relative_to(ROOT)}")

    headline(rows, args.markdown)
    scaling(rows, "n_agents", args.markdown)
    scaling(rows, "density", args.markdown)
    knob(rows, "beta", "beta", args.markdown, [
        ("mean_agents_changed", "agents changed", "{:.2f}"),
        ("total_timesteps", "total steps", "{:.0f}"),
        ("completion_rate", "tasks done", "{:.1%}"),
    ])
    knob(rows, "tau", "tau", args.markdown, [
        ("mean_reported_changes", "changes broadcast", "{:.2f}"),
        ("mean_agents_changed", "changes made", "{:.2f}"),
        ("total_timesteps", "total steps", "{:.0f}"),
    ])
    knob(rows, "k_max", "k_max", args.markdown, [
        ("mean_agents_changed", "agents changed", "{:.2f}"),
        ("total_timesteps", "total steps", "{:.0f}"),
        ("mean_repair_ms", "repair ms", "{:.1f}"),
        ("repair_failures", "failures", "{:.2f}"),
    ])
    knob(rows, "epsilon", "epsilon", args.markdown, [
        ("mean_repair_ms", "repair ms", "{:.1f}"),
        ("mean_repair_cycles", "ADOPT cycles", "{:.1f}"),
        ("mean_repair_messages", "messages", "{:.0f}"),
        ("total_timesteps", "total steps", "{:.0f}"),
    ])
    social_laws(rows, args.markdown)
    robustness(rows, args.markdown)
    print()


if __name__ == "__main__":
    main()
